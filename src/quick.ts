// Quick tunnels (names without a dot in config/cfproxy.yml): one cloudflared container each, with a random
// trycloudflare.com hostname and no Cloudflare account. Everything about them is here; the daemon only calls in.
//
// The containers, including the one running this machine's named tunnel when there is a token, are compose services
// in config/compose.tunnels.yaml, generated from config/cfproxy.yml and the x-cloudflared block of compose.yaml.
// The daemon cannot run compose itself, so ./cfproxy swaps the file in and starts them: this writes the next version
// beside it (.new), and ./cfproxy removes the services that are gone and brings up the rest.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fail, isQuick, loadConfig, loadSecrets, own, serviceUrl } from "./config";

export const COMPOSE_PATH = "/config/compose.tunnels.yaml";
// The checkout is mounted as a directory: a file mount would keep showing an old compose.yaml replaced by rename.
const BASE_PATH = "/host/cfproxy/compose.yaml";
// Above cloudflared's own default metrics ports (20241-20245), which the named tunnel's container takes.
const FIRST_METRICS_PORT = 20300;
const HEADER = `# Generated by cfproxy from config/cfproxy.yml and the x-cloudflared block of compose.yaml: do not edit.
# ./cfproxy add, rm and apply rewrite it and start or remove the containers.
`;

const quickTunnels = () => Object.entries(loadConfig().tunnels).filter(([name]) => isQuick(name));

type Service = { command: string[]; [key: string]: unknown };
const quickService = (name: string) => `quick-${name}`;

const readServices = (path: string): Record<string, Service> => (existsSync(path) ? (Bun.YAML.parse(readFileSync(path, "utf8")) as any)?.services ?? {} : {});

// The port a quick tunnel's container serves its metrics on (its URL and readiness), from its command.
const metricsPort = (service?: Service) => {
  const i = service?.command?.indexOf("--metrics") ?? -1;
  return i < 0 ? undefined : Number(service!.command[i + 1].split(":").pop());
};
const get = (port: number, path: string) => fetch(`http://127.0.0.1:${port}${path}`, { signal: AbortSignal.timeout(1500) });

// The containers and this one share the host's network, where other programs (or another cfproxy checkout) may hold a
// port: one is only used when nothing listens on it, or when it is this tunnel's own container, which /debug/vars
// tells by its command line.
const isFree = (port: number) => {
  try {
    return Bun.listen({ hostname: "127.0.0.1", port, socket: { data() {} } }).stop(true), true;
  } catch {
    return false;
  }
};
const isOurs = async (service: Service) =>
  JSON.stringify(await get(metricsPort(service)!, "/debug/vars").then((r) => r.json()).then((v: any) => v.cmdline.slice(-service.command.length)).catch(() => 0)) === JSON.stringify(service.command);

// What the containers should be now. A quick tunnel keeps its metrics port across rewrites while it is still free or its
// own: a new port would change its command, compose would recreate it, and Cloudflare would hand it a new URL.
async function desiredServices() {
  const base = (Bun.YAML.parse(readFileSync(BASE_PATH, "utf8")) as any)?.["x-cloudflared"] ?? fail("compose.yaml has no x-cloudflared block");
  const applied = readServices(COMPOSE_PATH);
  const quick = quickTunnels();
  const services: Record<string, Service> = {};

  if (loadSecrets().apiToken)
    services.cloudflared = { ...base, command: ["tunnel", "--no-autoupdate", "run", "--token-file", "/state/token"], volumes: ["state:/state:ro"] };

  const kept = new Map<string, number>();
  for (const [name] of quick) {
    const running = applied[quickService(name)];
    const port = metricsPort(running);
    if (port && ![...kept.values()].includes(port) && (isFree(port) || (await isOurs(running)))) kept.set(name, port);
  }
  const used = new Set(kept.values());
  let next = FIRST_METRICS_PORT;
  for (const [name, addr] of quick) {
    let port = kept.get(name);
    if (!port) {
      while (used.has(next) || !isFree(next)) next++;
      used.add((port = next));
    }
    services[quickService(name)] = { ...base, command: ["tunnel", "--no-autoupdate", "--metrics", `127.0.0.1:${port}`, "--url", serviceUrl(addr)] };
  }
  return services;
}

// For ./cfproxy, which then swaps it in.
export async function writeCompose() {
  writeFileSync(`${COMPOSE_PATH}.new`, `${HEADER}${Bun.YAML.stringify({ services: await desiredServices() }, null, 2)}\n`);
  own(`${COMPOSE_PATH}.new`);
}

// The containers that differ between the config and what ./cfproxy last started (new, changed or gone).
async function pendingChanges() {
  const want = await desiredServices();
  const have = readServices(COMPOSE_PATH);
  return Object.keys({ ...have, ...want })
    .filter((name) => JSON.stringify(want[name]?.command) !== JSON.stringify(have[name]?.command))
    .map((name) => (name.startsWith("quick-") ? `quick tunnel ${name.slice(6)}` : `container ${name}`));
}

export const printPlan = async () => (await pendingChanges()).forEach((change) => console.log(`(plan) ~ ${change}`));

// --- quick tunnels as they run now ---

type QuickState = { name: string; service: string; url?: string; state: string };

// From the container's metrics server: /quicktunnel has the hostname Cloudflare assigned, /ready says whether it is
// connected. Its container may have been stopped or removed outside cfproxy, or not have started yet.
async function probe(service: Service) {
  const port = metricsPort(service)!;
  if (isFree(port)) return { state: "not running (still starting, or stopped: ./cfproxy apply starts it)" };
  if (!(await isOurs(service))) return { state: `port ${port} is taken by another program (./cfproxy apply moves it)` };
  const { hostname } = (await (await get(port, "/quicktunnel")).json()) as { hostname?: string };
  const ready = (await get(port, "/ready")).ok;
  return { url: hostname ? `https://${hostname}` : undefined, state: !hostname ? "starting" : ready ? "ok" : "connecting" };
}

async function quickStatus(): Promise<QuickState[]> {
  const applied = readServices(COMPOSE_PATH);
  return Promise.all(
    quickTunnels().map(async ([name, addr]) => {
      const service = serviceUrl(addr);
      const running = applied[quickService(name)];
      if (!running || !running.command.includes(service)) return { name, service, state: "not applied (./cfproxy apply)" };
      return { name, service, ...(await probe(running).catch(() => ({ state: "not responding (see its container's logs)" }))) };
    }),
  );
}

export async function printStatus() {
  for (const { name, service, url, state } of await quickStatus())
    console.log(`${url ?? `quick tunnel ${name}`} -> ${service}   quick tunnel ${name}: ${state}`);
  for (const change of await pendingChanges()) console.log(`not applied yet (./cfproxy apply): ${change}`);
}

// After ./cfproxy add started it (same arguments as add): Cloudflare assigns the hostname within seconds of the
// container connecting. An SSH tunnel also gets the command that sets up a client for it.
export async function printUrl([, name]: string[]) {
  if (!isQuick(name)) return;
  let tunnel: QuickState | undefined;
  for (const until = Date.now() + 30_000; !tunnel?.url && Date.now() < until; await Bun.sleep(1000))
    tunnel = (await quickStatus()).find((t) => t.name === name.toLowerCase());
  if (!tunnel?.url) return console.log(`quick tunnel ${name}: no URL yet (${tunnel?.state ?? "not in the config"}); ./cfproxy status shows it once it is up`);
  console.log(`${tunnel.url} -> ${tunnel.service}   (a new URL each time the tunnel restarts; ./cfproxy status shows it)`);
  if (tunnel.service.startsWith("ssh://")) console.log(`on a client: ./cfproxy ssh ${name}=<user>@${new URL(tunnel.url).hostname.replace(/\.trycloudflare\.com$/, "")}`);
}
